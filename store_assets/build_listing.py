"""Checks the Play limits of store_assets/listing_data.py and writes
store_assets/PLAY_STORE_LISTING.md.

Run from the repository root:  python store_assets/build_listing.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from listing_data import LISTINGS  # noqa: E402

LIMITS = {'title': 30, 'short': 80, 'full': 4000}
APP_LOCALES = {'en', 'he', 'es', 'pt', 'pt_BR', 'id', 'hi', 'fil', 'ar', 'fr',
               'de', 'ru', 'pl', 'tr', 'ja', 'ko', 'zh', 'zh_TW', 'vi', 'my',
               'bn', 'tt'}
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   'PLAY_STORE_LISTING.md')


def main():
    errors = []
    seen = {l['app'] for l in LISTINGS}
    if seen != APP_LOCALES:
        errors.append(f'locales differ from the app: {sorted(seen ^ APP_LOCALES)}')
    for l in LISTINGS:
        for field, limit in LIMITS.items():
            n = len(l[field])
            if n > limit:
                errors.append(f"{l['app']} {field}: {n} > {limit}")
    if errors:
        sys.exit('\n'.join(errors))

    out = ['# CubeMentor - Google Play Store Listing', '',
           'Generated by `python store_assets/build_listing.py` from',
           '`store_assets/listing_data.py` (edit the data file, then rebuild).',
           'Each block is ready to paste into Play Console > Grow > Store',
           'presence > Main store listing > (language).', '',
           'Limits: app name <= 30, short description <= 80, full description',
           '<= 4,000 characters; the counts below are checked on every build.', '',
           '**Policy notes.** No third-party trademarks in the metadata; the',
           'daily leaderboard is described as offline with simulated rivals,',
           'matching the disclosure inside the app. Tatar has no Play listing',
           'language; its text is kept for the website or other stores.', '',
           '## Graphic assets', '',
           '| Asset | File | Size |', '|---|---|---|',
           '| Hi-res icon | `store_assets/PLAY_ICON_512.png` | 512 x 512 |',
           '| Feature graphic | `store_assets/FEATURE_GRAPHIC.png` | 1024 x 500 |',
           '| Phone screenshots | `python store_assets/frame_screenshots.py --in <raw> --out <framed> --locale <code>` | 1080 x 1920 |',
           '', 'Regenerate the icon and feature graphic with',
           '`python tool/generate_app_icon.py` and',
           '`python tool/generate_feature_graphic.py`.', '',
           '## Languages', '']
    for l in LISTINGS:
        out.append(f"- [{l['name']}](#{l['app'].lower().replace('_', '-')}) "
                   f"(`{l['play']}`)")
    out.append('')
    for l in LISTINGS:
        anchor = l['app'].lower().replace('_', '-')
        out += [f'<a id="{anchor}"></a>', '',
                f"## {l['name']} — app `{l['app']}`, Play `{l['play']}`", '',
                f"**App name** ({len(l['title'])}/30)", '', '```text',
                l['title'], '```', '',
                f"**Short description** ({len(l['short'])}/80)", '', '```text',
                l['short'], '```', '',
                f"**Full description** ({len(l['full'])}/4000)", '', '```text',
                l['full'], '```', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print(f'wrote {OUT}: {len(LISTINGS)} languages')


if __name__ == '__main__':
    main()
